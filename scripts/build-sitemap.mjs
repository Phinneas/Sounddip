#!/usr/bin/env node
/**
 * Generates public/sitemap.xml from the published-city allowlist and the blog
 * collection, so the sitemap cannot drift from what the site actually serves.
 *
 * It replaced a hand-maintained sitemap.xml that had drifted in both directions:
 * it listed 35 city pages that fall below the inventory threshold, and it had
 * lost three blog posts that were live and linked but absent from the sitemap.
 *
 * Runs as a `prebuild` hook — see package.json. Deliberately emits only <loc>:
 * a wrong <lastmod> is worse than none, and the only reliable dates in the repo
 * are blog pubDates.
 *
 * Usage:
 *   node scripts/build-sitemap.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://www.sounddip.com';
const OUT = path.join(ROOT, 'public', 'sitemap.xml');

// Non-generated pages. Explicit rather than globbed from src/pages so that
// adding a page never silently puts it in the sitemap.
const STATIC_PATHS = [
  '/',
  '/cities/',
  '/find-your-dip/',
  '/submit/',
  '/verify/',
  '/about/',
  '/privacy/',
  '/terms/',
  '/articles/',
  '/guide/first-time/',
  '/blog/',
];

/** Slugs from the PUBLISHED_SLUGS allowlist in src/data/cities.ts. */
function publishedCitySlugs() {
  const src = fs.readFileSync(path.join(ROOT, 'src', 'data', 'cities.ts'), 'utf8');
  const block = src.match(/const PUBLISHED_SLUGS[^=]*=\s*\[([\s\S]*?)\n\];/);
  if (!block) throw new Error('Could not find PUBLISHED_SLUGS in src/data/cities.ts');
  const slugs = [...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
  if (slugs.length === 0) throw new Error('PUBLISHED_SLUGS parsed empty — refusing to write a sitemap');
  return slugs;
}

/** Blog slugs, from the content collection filenames. */
function blogSlugs() {
  const dir = path.join(ROOT, 'src', 'content', 'blog');
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.mdx'))
    .map((f) => f.replace(/\.mdx$/, ''))
    .sort();
}

function main() {
  const cities = publishedCitySlugs();
  const posts = blogSlugs();

  // Trailing slashes everywhere: astro.config.mjs sets trailingSlash: 'always',
  // so a sitemap URL without one would 301 on every crawl.
  const urls = [
    ...STATIC_PATHS,
    ...cities.map((slug) => `/cities/${slug}/`),
    ...posts.map((slug) => `/blog/${slug}/`),
  ];

  const dupes = urls.filter((u, i) => urls.indexOf(u) !== i);
  if (dupes.length) throw new Error(`Duplicate sitemap URLs: ${dupes.join(', ')}`);

  const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- Generated by scripts/build-sitemap.mjs — do not edit by hand. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map((u) => `  <url><loc>${SITE}${u}</loc></url>`).join('\n') +
    `\n</urlset>\n`;

  fs.writeFileSync(OUT, xml);
  console.log(
    `sitemap.xml: ${urls.length} URLs ` +
      `(${STATIC_PATHS.length} static, ${cities.length} cities, ${posts.length} blog posts)`,
  );
}

main();
